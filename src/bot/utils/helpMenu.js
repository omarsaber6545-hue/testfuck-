function getHelpNavRow(current) {
  return createRow(
    createButton({ customId: 'help_nav_main', label: 'الرئيسية', style: current === 'main' ? ButtonStyle.Primary : ButtonStyle.Secondary }),
    createButton({ customId: 'help_nav_bank', label: 'أوامر البنك 🏦', style: current === 'bank' ? ButtonStyle.Primary : ButtonStyle.Secondary }),
    createButton({ customId: 'help_nav_games', label: 'أوامر الألعاب 🎮', style: current === 'games' ? ButtonStyle.Primary : ButtonStyle.Secondary }),
    createButton({ customId: 'help_nav_admin', label: 'أوامر الأونرز 👑', style: current === 'admin' ? ButtonStyle.Primary : ButtonStyle.Secondary })
  );
}

